/**
 * Roast my team (7.8, kasvutemppu 2) — sama rate-team-data, piikikäs sävy.
 *
 * MIKSI: arvosana/roast on UGC-generaattori — hauska tai piikikäs arvio
 * jaetaan herkemmin kuin neutraali (tutkimus 7.8: RMT→roast-formaatti,
 * FPL Copilot tekee kilttiä versiota; roast + oikea malli takana on aukko).
 *
 * SÄÄNNÖT: piikki kohdistuu AINA joukkueeseen/valintoihin, ei käyttäjään
 * henkilönä; ei kirosanoja; jokainen väite nojaa payloadin lukuun (roast
 * jonka numerot ovat oikein on parempi roast). Ei em dashia (copy-sääntö).
 * Kaikki rivit deterministisiä — sama data, sama roast → jaettu tulos on
 * toistettavissa eikä arvonta.
 */
import type { RateTeamResponse, RatedPlayer } from '$lib/fantasyTools';

function worstValueXi(players: RatedPlayer[]): RatedPlayer | null {
	const xi = players.filter((p) => p.in_xi && p.price >= 6.0 && p.xp_per_gw > 0);
	if (!xi.length) return null;
	return xi.reduce((worst, p) =>
		p.price / p.xp_per_gw > worst.price / worst.xp_per_gw ? p : worst
	);
}

function benchOutscoresXi(players: RatedPlayer[]): { bench: RatedPlayer; xi: RatedPlayer } | null {
	for (const b of players.filter((p) => !p.in_xi)) {
		const victim = players
			.filter((p) => p.in_xi && p.pos === b.pos && p.xp_per_gw < b.xp_per_gw - 0.3)
			.sort((a, z) => a.xp_per_gw - z.xp_per_gw)[0];
		if (victim) return { bench: b, xi: victim };
	}
	return null;
}

export function buildRoast(data: RateTeamResponse): string[] {
	const lines: string[] = [];
	const r = data.rating;
	const score = r.rating ?? Math.round(r.percentile ?? 0);

	if (r.beats_benchmark) {
		lines.push(
			'Your XI beats the best squad the model can build. We have nothing. This is deeply annoying and we respect it.'
		);
	} else if (score >= 85) {
		lines.push(
			`${score}/100. Annoyingly competent. The model found almost nothing to mock, and it looked hard.`
		);
	} else if (score >= 70) {
		lines.push(
			`${score}/100. A solid pub-team answer to a question nobody asked. The template called, it wants royalties.`
		);
	} else if (score >= 50) {
		lines.push(
			`${score}/100. Half the projected points the rules allow. The other half is presumably a lifestyle choice.`
		);
	} else {
		lines.push(
			`${score}/100. The model has projected two million squads and would still like to unsee this one.`
		);
	}

	if (typeof r.gap_to_optimal_xp === 'number' && r.gap_to_optimal_xp > 5) {
		lines.push(
			`You are leaving ${r.gap_to_optimal_xp.toFixed(1)} projected points on the table over the horizon. That is not a differential strategy, that is a donation.`
		);
	}

	if (r.weakest_line) {
		lines.push(
			`Weakest line: ${r.weakest_line.toLowerCase()}. It is doing charity work while the rest of the squad carries it.`
		);
	}

	const wv = worstValueXi(data.team?.players ?? []);
	if (wv) {
		lines.push(
			`${wv.price.toFixed(1)}m on ${wv.web_name} for ${wv.xp_per_gw.toFixed(2)} xP a week. Per point, that is luxury pricing for a budget product.`
		);
	}

	const cap = data.captain?.pick;
	const armband = (data.team?.players ?? []).find((p) => p.is_captain);
	if (cap && armband && armband.id !== cap.id) {
		lines.push(
			`The armband is on ${armband.web_name} while the model's pick ${cap.web_name} (${cap.gw_xp.toFixed(1)} xP) watches. Bold. Wrong, but bold.`
		);
	}

	const bo = benchOutscoresXi(data.team?.players ?? []);
	if (bo) {
		lines.push(
			`${bo.bench.web_name} projects more than ${bo.xi.web_name} and still rides your bench. He saw the team sheet. He knows.`
		);
	}

	lines.push(
		'Roast generated by a match model with a public track record. It earned the right to talk.'
	);
	return lines;
}

/** Roastin taso: kortti ja teksti johdetaan SAMASTA luvusta.
 *
 * 🔴 Miksi tama on funktio eika kortin oma if-ketju: jos kortti laskisi
 * tason itse, sama joukkue voisi saada tekstin "annoyingly competent" ja
 * kuvan jossa se palaa. Yksi lahde, kaksi pintaa. Sama syy kuin sille
 * ettei klientti laske pisteita Beat the Modelissa.
 */
export type RoastTier = 'singed' | 'toasted' | 'cremated';

export function roastTier(data: RateTeamResponse): { tier: RoastTier; score: number } {
	const r = data.rating;
	const score = r.rating ?? Math.round(r.percentile ?? 0);
	if (r.beats_benchmark || score >= 70) return { tier: 'singed', score };
	if (score >= 50) return { tier: 'toasted', score };
	return { tier: 'cremated', score };
}

/** Kortin ja jaon kuvateksti. Yksi rivi, koska kortti kantaa loput. */
export function roastHeadline(tier: RoastTier): string {
	if (tier === 'singed') return 'BARELY SINGED';
	if (tier === 'toasted') return 'TOASTED';
	return 'CREMATED';
}
